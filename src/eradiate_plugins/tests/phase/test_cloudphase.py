def _to_ordered_uint(x: np.floating) -> int:
    nb       = x.itemsize * 8
    bits     = int(x.view(UINT_DTYPES[nb]))
    sign_bit = 1 << (nb - 1)
    all_ones = (1 << nb) - 1
    if bits == sign_bit:
        bits = 0
    if bits & sign_bit:
        bits ^= all_ones
    else:
        bits |= sign_bit
    if bits < sign_bit:
        bits += 1
    return bits


def _from_ordered_uint(i: int, dtype) -> np.floating:
    nb       = np.dtype(dtype).itemsize * 8
    sign_bit = 1 << (nb - 1)
    all_ones = (1 << nb) - 1
    if i < sign_bit:
        i -= 1
    if i & sign_bit:
        i ^= sign_bit
    else:
        i ^= all_ones
    return np.array(i, dtype=UINT_DTYPES[nb]).view(dtype)[()]


def _sample_unique_uints(lo: int, hi: int, k: int) -> np.ndarray:
    """
    Sample k unique integers uniformly from (lo, hi) exclusive.
    Uses rejection sampling — O(k) for sparse ranges (float32/64),
    falls back to np.random.choice for dense ranges (float16).
    """
    interior = hi - lo - 1   # number of available interior slots

    if interior < 3 * k:
        # Dense: population small enough for choice (float16 territory)
        return np.sort(
            np.random.choice(interior, size=k, replace=False).astype(np.int64) + lo + 1
        )

    # Sparse: rejection sampling — expected ~k * (1 + k/interior) samples
    result = set()
    while len(result) < k:
        needed  = k - len(result)
        samples = np.random.randint(lo + 1, hi, size=needed + 16, dtype=np.int64)
        result.update(samples.tolist())
    return np.array(sorted(result)[:k], dtype=np.int64)


def monotonic_floats(a: float, b: float, n: int, precision: int = 16) -> np.ndarray:
    """
    Generate n strictly monotonic floats between a and b (inclusive)
    with uniformly random interior values.
    """
    if precision not in FLOAT_DTYPES:
        raise ValueError(f"precision must be 16, 32, or 64. Got {precision}.")
    if n < 2:
        raise ValueError("n must be at least 2.")

    dtype = FLOAT_DTYPES[precision]
    a, b  = dtype(a), dtype(b)

    if not (np.isfinite(a) and np.isfinite(b)):
        raise ValueError(f"a and b must be finite in float{precision}.")
    if a == b:
        raise ValueError(f"a and b are equal or indistinguishable in float{precision}.")

    ascending = b > a
    lo, hi    = (a, b) if ascending else (b, a)

    lo_uint   = _to_ordered_uint(lo)
    hi_uint   = _to_ordered_uint(hi)
    ulp_steps = hi_uint - lo_uint

    if ulp_steps < n - 1:
        raise ValueError(
            f"Cannot fit {n} strictly monotonic float{precision} values between "
            f"{a} and {b}: only {ulp_steps + 1} representable values exist "
            f"in that interval (need {n})."
        )

    if n == 2:
        return np.array([lo, hi] if ascending else [hi, lo], dtype=dtype)

    inner_uints = _sample_unique_uints(lo_uint, hi_uint, n - 2)

    all_uints = np.concatenate([[lo_uint], inner_uints, [hi_uint]])
    combined  = np.array([_from_ordered_uint(int(i), dtype) for i in all_uints], dtype=dtype)

    assert np.all(np.diff(combined) > 0), "BUG: monotonicity violated."

    return combined if ascending else combined[::-1].copy()


def generate_n_mueller(n, s=6, min_points=164, max_points=1000):

    """
    Using Henyey-Greenstein, generate n * s phase functions to
    fill n polarized tabulated phase functions. Default to 6 phases
    in order to emulate spherical polarized particles media.

    Map the phases on incompatible irregular angular grids,
    generated by sampling cos. There is no guarantee that the
    cos grid is sensible to sample the phase, and the physicallity
    of the phase is not assessed. This is for test purposes.

    The number of generated points per s-sized set of phases resides
    in [min_points; max_points[.

    This function is deterministic.
    """

    if n <1:
        raise ValueError("n must be superior to 1")
    if s <1:
        raise ValueError("s must be superior to 1")
    if min_points <2:
        raise ValueError("min_points must be superior to 2")
    if max_points <= min_points:
        raise ValueError("max_points must be superior to min_points")
    
    rng = np.random.default_rng(0)
    
    grid_len = rng.integers(min_points, max_points, n)
    grid_start = np.cumsum(grid_len)
    total_points = grid_start[-1]
    grid_start = grid_start - grid_len

    nodes = np.empty(total_points, dtype=np.float32)
    for i in range(n):
        st = grid_start[i]
        le = grid_len[i]
        en = st + le
        nodes[st:en] = monotonic_floats(-1.0, 1.0, le, precision=32)
        assert nodes[st] == -1.0
        assert nodes[en - 1] == 1.0

    idx = np.concatenate([np.full(grid_len[i], i) for i in range(n)])

    g = rng.random((n, s)) * 2.0 - 1.0
    P_hg = np.empty((total_points, s))

    for j in range(s):
        gj = g[:, j][idx]          # (total_points,) — one column
        gj_2 = gj * gj
        gj_mu = nodes * gj
        denom = 1.0 + gj_2 - 2.0 * gj_mu  # (total_points,)
        denom = denom * np.sqrt(denom)      # x^1.5 = x * sqrt(x)
        P_hg[:, j] = (1.0 - gj_2) / denom

    P_hg *= 1.0 / (4.0 * np.pi)

    return rng, nodes, grid_start, grid_len, P_hg


