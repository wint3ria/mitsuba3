def test_stress_vs_tabphase(tabphase_plugin, cloudphase_single):
    import time

    N = 100000
    rng = np.random.default_rng(99)
    wis = rng.random((N, 3)) * 2 - 1
    wis /= np.linalg.norm(wis, axis=1, keepdims=True)
    wos = rng.random((N, 3)) * 2 - 1
    wos /= np.linalg.norm(wos, axis=1, keepdims=True)
    ps  = rng.random((N, 3))

    ctx = mi.PhaseFunctionContext(None)
    mei = mi.MediumInteraction3f()

    t0 = time.perf_counter()
    for i in range(N):
        mei.wi = mi.Vector3f(wis[i])
        mei.p  = mi.Point3f(ps[i])
        tabphase_plugin.eval_pdf(ctx, mei, mi.Vector3f(wos[i]))
    t_tab = (time.perf_counter() - t0) / N * 1e6

    t0 = time.perf_counter()
    for i in range(N):
        mei.wi = mi.Vector3f(wis[i])
        mei.p  = mi.Point3f(ps[i])
        cloudphase_single.eval_pdf(ctx, mei, mi.Vector3f(wos[i]))
    t_cloud = (time.perf_counter() - t0) / N * 1e6

    assert (t_cloud - t_tab) / t_tab < 0.3

    print(f"\ntabphase_polarized:  {t_tab:.2f} us/call")
    print(f"cloudphase (single): {t_cloud:.2f} us/call")
    print(f"ratio:               {t_tab/t_cloud:.2f}x")


def test_correctness_vs_tabphase(tabphase_plugin, cloudphase_single, single_phase_data):
    nodes, grid_start, grid_len, P_hg = single_phase_data

    rng = np.random.default_rng(42)
    ctx = mi.PhaseFunctionContext(None)
    mei = mi.MediumInteraction3f()

    for i in range(100):
        wi = rng.random(3) * 2 - 1
        wi /= np.linalg.norm(wi)
        wo = rng.random(3) * 2 - 1
        wo /= np.linalg.norm(wo)

        mei.wi = mi.Vector3f(wi)
        mei.p  = mi.Point3f(rng.random(3))

        val_tab,   pdf_tab   = tabphase_plugin.eval_pdf(ctx, mei, mi.Vector3f(wo))
        val_cloud, pdf_cloud = cloudphase_single.eval_pdf(ctx, mei, mi.Vector3f(wo))

        assert np.isclose(float(pdf_tab), float(pdf_cloud), rtol=1e-4, atol=1e-7), \
            f"[i={i}] pdf mismatch: tabphase={float(pdf_tab):.8f}, " \
            f"cloudphase={float(pdf_cloud):.8f}, cos_t={-np.dot(wo, wi):.4f}"

        val_tab_np   = val_tab.numpy()
        val_cloud_np = val_cloud.numpy()
        assert np.allclose(val_tab_np, val_cloud_np, rtol=1e-4, atol=1e-7), \
            f"[i={i}] Mueller matrix mismatch:\n" \
            f"tabphase:\n{val_tab_np}\ncloudphase:\n{val_cloud_np}"
