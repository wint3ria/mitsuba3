def reference_eval_pdf(nodes, grid_start, grid_len, P_hg, index, wi, wo):
    start  = grid_start[index]
    length = grid_len[index]
    entry_nodes   = nodes[start : start + length]
    entry_mueller = P_hg[start : start + length, :]

    cos_t = float(np.clip(-np.dot(wo, wi), -1.0, 1.0))

    idx = np.searchsorted(entry_nodes, cos_t, side='left')
    idx = np.clip(idx, 1, length - 1)
    lo, hi = idx - 1, idx
    x0, x1 = entry_nodes[lo], entry_nodes[hi]
    t = (cos_t - x0) / (x1 - x0) if (x1 - x0) > 0 else 0.0
    m = entry_mueller[lo] + t * (entry_mueller[hi] - entry_mueller[lo])

    dx       = np.diff(entry_nodes)
    m11_vals = entry_mueller[:, 0]
    integral = float(np.sum(0.5 * (m11_vals[:-1] + m11_vals[1:]) * dx))

    norm = 1.0 / (integral * 2.0 * np.pi) if integral > 0 else 0.0
    pdf  = float(m[0] * norm)

    # build raw Mueller matrix
    mueller = mi.Spectrum([
        [ float(m[0]),  float(m[1]),  0.0,          0.0         ],
        [ float(m[1]),  float(m[2]),  0.0,          0.0         ],
        [ 0.0,          0.0,          float(m[3]),  float(m[4]) ],
        [ 0.0,          0.0,         -float(m[4]),  float(m[5]) ],
    ]) * float(norm)

    # radiance mode: wo_hat=wo, wi_hat=wi
    wo_hat = mi.Vector3f(wo)
    wi_hat = mi.Vector3f(wi)

    x_hat      = dr.cross(-wo_hat, wi_hat)
    p_axis_in  = dr.normalize(dr.cross(x_hat, -wo_hat))
    p_axis_out = dr.normalize(dr.cross(x_hat,  wi_hat))

    mueller = mi.mueller.rotate_mueller_basis(
        mueller,
        -wo_hat, p_axis_in,  mi.mueller.stokes_basis(-wo_hat),
         wi_hat, p_axis_out, mi.mueller.stokes_basis( wi_hat)
    )

    return mueller.numpy()[:, :, 0], pdf


def get_index_at(index_array, p):
    # index_array shape is (1500, 100, 100) = (nz, ny, nx) in mitsuba's convention
    nz, ny, nx = index_array.shape
    ix = int(np.clip(p[0] * nx, 0, nx - 1))
    iy = int(np.clip(p[1] * ny, 0, ny - 1))
    iz = int(np.clip(p[2] * nz, 0, nz - 1))
    return int(index_array[iz, iy, ix])


def test_eval_pdf_reference(large_phase_data, large_phase_plugin):
    nodes, grid_start, grid_len, P_hg, index_array = large_phase_data
    _, phase = large_phase_plugin

    P_hg_2d = P_hg.reshape(-1, 6)

    ctx = mi.PhaseFunctionContext(None)
    mei = mi.MediumInteraction3f()
    rng = np.random.default_rng(42)

    for i in range(100):
        # non-degenerate random directions
        wi = rng.random(3) * 2 - 1
        wi /= np.linalg.norm(wi)
        wo = rng.random(3) * 2 - 1
        wo /= np.linalg.norm(wo)
        p  = rng.random(3)

        mei.wi = mi.Vector3f(wi)
        mei.p  = mi.Point3f(p)

        # mitsuba evaluation
        val, pdf = phase.eval_pdf(ctx, mei, mi.Vector3f(wo))

        # index from construction array
        index = get_index_at(index_array, p)

        # numpy reference — note: no Stokes rotation applied here,
        ref_mueller, ref_pdf = reference_eval_pdf(
            nodes, grid_start, grid_len, P_hg_2d, index, wi, wo
        )

        val, pdf = phase.eval_pdf(ctx, mei, mi.Vector3f(wo))
        index = get_index_at(index_array, p)
        ref_mueller, ref_pdf = reference_eval_pdf(
            nodes, grid_start, grid_len, P_hg_2d, index, wi, wo
        )

        # pdf check — not affected by Stokes rotation
        assert np.isclose(float(pdf), ref_pdf, rtol=1e-4, atol=1e-7), \
            f"[i={i}] pdf mismatch: got {float(pdf):.8f}, expected {ref_pdf:.8f}\n" \
            f"  index={index}, cos_t={-np.dot(wo,wi):.4f}"

        # Mueller check — Stokes rotation makes full matrix comparison
        # unreliable without reimplementing rotate_mueller_basis in numpy.
        # Check only M11 which is rotation-invariant.
        val_np = val.numpy()[:, :, 0]
        assert np.allclose(val_np, ref_mueller, rtol=1e-4, atol=1e-7), \
            f"[i={i}] Mueller mismatch:\ngot:\n{val_np}\nexpected:\n{ref_mueller}"


